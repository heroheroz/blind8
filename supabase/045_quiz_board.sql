-- 045：測驗積分榜（主人 11月14日）。每題只計第一次答，答啱 1 分；同貢獻積分完全分開。
-- 每星期（星期一香港時間零時起）頭 50 題計分，之後照記低（scored=false，當練習），嗰啲題以後都唔再計分。
-- quiz_key：答案表（前端讀唔到，只畀 quiz_answer 對答案）；題目改咗要重新同步呢張表（scripts 用 quiz.json 出）。
create table if not exists public.quiz_key (qid text primary key, ans smallint not null);
alter table public.quiz_key enable row level security;
create table if not exists public.quiz_answers (
  user_id uuid not null references auth.users(id) on delete cascade,
  qid text not null, pick smallint not null, correct boolean not null, scored boolean not null default true,
  at timestamptz not null default now(), primary key (user_id, qid));
alter table public.quiz_answers enable row level security;
do $$ begin
  if not exists (select 1 from pg_policies where tablename='quiz_answers' and policyname='quiz_answers_own') then
    create policy quiz_answers_own on public.quiz_answers for select using (user_id = auth.uid());
  end if; end $$;
-- 唔上榜嘅戶口（測試戶口、洗分）：管理員入
create table if not exists public.quiz_hidden (user_id uuid primary key);
alter table public.quiz_hidden enable row level security;

create or replace function public.quiz_answer(p_qid text, p_pick int) returns jsonb
language plpgsql security definer set search_path = public as $$
declare k smallint; n int; td int; cap constant int := 50;
begin
  if auth.uid() is null then return jsonb_build_object('ok', false); end if;
  select ans into k from quiz_key where qid = p_qid;
  if k is null then return jsonb_build_object('ok', false); end if;
  select count(*) into td from quiz_answers where user_id = auth.uid() and scored
    and at >= date_trunc('week', now() at time zone 'Asia/Hong_Kong') at time zone 'Asia/Hong_Kong';
  insert into quiz_answers(user_id, qid, pick, correct, scored) values (auth.uid(), p_qid, p_pick, p_pick = k, td < cap)
    on conflict (user_id, qid) do nothing;
  get diagnostics n = row_count;
  return jsonb_build_object('ok', true, 'first', n = 1, 'scored', n = 1 and td < cap, 'today', least(cap, td + case when n = 1 and td < cap then 1 else 0 end), 'cap', cap);
end $$;
grant execute on function public.quiz_answer(text, int) to authenticated;

-- 排名：先睇分數（答啱題數），同分睇答啱率，再同睇邊個早
create or replace function public.quiz_rank(p_from timestamptz) returns table(uid uuid, name text, title text, score int, n int, rk int)
language sql stable security definer set search_path = public as $$
  with g as (
    select a.user_id, count(*) filter (where a.correct)::int as score, count(*)::int as n, max(a.at) as last_at
    from quiz_answers a
    where a.scored and (p_from is null or a.at >= p_from) and not exists (select 1 from quiz_hidden h where h.user_id = a.user_id)
    group by a.user_id)
  select g.user_id,
         (select left(btrim(v), 30) from unnest(array[au.raw_user_meta_data->>'full_name', au.raw_user_meta_data->>'name']) with ordinality t(v, o)
          where v is not null and btrim(v) <> '' and v !~ '@' order by o limit 1),
         coalesce((select t.title from user_titles t where t.user_id = g.user_id), '師兄'),
         g.score, g.n,
         row_number() over (order by g.score desc, g.score::float / g.n desc, g.last_at)::int
  from g left join auth.users au on au.id = g.user_id where g.score > 0
$$;
revoke execute on function public.quiz_rank(timestamptz) from public, anon, authenticated;

create or replace function public.quiz_week() returns timestamptz language sql stable as
$$ select date_trunc('week', now() at time zone 'Asia/Hong_Kong') at time zone 'Asia/Hong_Kong' $$;

-- 測驗頁個榜：頭 20 名＋自己嗰行
create or replace function public.quiz_board(p_week boolean) returns table(rk int, name text, title text, score int, n int, me boolean)
language sql stable security definer set search_path = public as $$
  select r.rk, r.name, r.title, r.score, r.n, r.uid = auth.uid()
  from quiz_rank(case when p_week then quiz_week() end) r
  where r.rk <= 20 or r.uid = auth.uid() order by r.rk
$$;
grant execute on function public.quiz_board(boolean) to anon, authenticated;

-- 走馬燈：本週頭 5 名
create or replace function public.quiz_top5() returns table(rk int, name text, title text, score int, n int)
language sql stable security definer set search_path = public as $$
  select r.rk, r.name, r.title, r.score, r.n from quiz_rank(quiz_week()) r where r.rk <= 5 order by r.rk
$$;
grant execute on function public.quiz_top5() to anon, authenticated;

